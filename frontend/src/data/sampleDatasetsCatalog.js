// Helper: Build Audited Results payload from arbitrary rows
export function buildAuditedPayloadFromRows(rows = [], datasetName = 'Custom_Healthcare_Claims.csv') {
  let flaggedCount = 0;
  let clearedCount = 0;
  let criticalCount = 0;
  let highCount = 0;
  let totalExposure = 0;
  let flaggedExposure = 0;

  const results = rows.map((row, idx) => {
    const totalReimb = (Number(row.inpatient_reimbursed_sum) || 0) + (Number(row.outpatient_reimbursed_sum) || 0) || 350000;
    totalExposure += totalReimb;

    let riskScore = 0.45;
    if (row.baseline_risk !== undefined) {
      riskScore = Number(row.baseline_risk);
    } else {
      const surg = Number(row.total_inpatient_surgeries || 0);
      const mds = Math.max(1, Number(row.unique_attending_physicians || 1));
      const los = Number(row.mean_inpatient_los || 3.0);
      const dups = Number(row.same_day_duplicate_rate || 0);
      const cent = Number(row.graph_degree_centrality || 0.2);

      let calc = 0.08;
      if (surg / mds > 60) calc += 0.55;
      if (los > 8.0) calc += 0.40;
      if (dups > 0.20) calc += 0.35;
      if (cent > 0.60) calc += 0.25;
      if (totalReimb > 4000000) calc += 0.20;
      riskScore = Math.min(0.999, Math.max(0.015, calc));
    }

    const isFlagged = riskScore >= 0.5364;
    const priority = riskScore >= 0.85 ? 'CRITICAL' : isFlagged ? 'HIGH' : riskScore >= 0.35 ? 'MEDIUM' : 'LOW';

    if (isFlagged) {
      flaggedCount++;
      flaggedExposure += totalReimb;
      if (priority === 'CRITICAL') criticalCount++;
      else highCount++;
    } else {
      clearedCount++;
    }

    const margin = Math.abs(riskScore - 0.5364);
    const confVal = Math.min(99.9, Math.max(74.0, (0.5 + margin * 0.98) * 100));
    const confTier = confVal >= 95 ? 'VERY HIGH' : confVal >= 85 ? 'HIGH' : confVal >= 75 ? 'MODERATE' : 'BORDERLINE';

    let topDriverFeature = 'Balanced Inpatient LOS & Surgery Ratio';
    let topDriverDesc = 'Clinical volume and physician ratios conform to standard institutional distributions';
    let topShap = -0.142;

    const surgCount = Number(row.total_inpatient_surgeries || 0);
    const mdsCount = Math.max(1, Number(row.unique_attending_physicians || 1));
    const losDays = Number(row.mean_inpatient_los || 0);
    const centScore = Number(row.graph_degree_centrality || 0);
    const dupRate = Number(row.same_day_duplicate_rate || 0);

    if (surgCount / mdsCount > 60) {
      topDriverFeature = 'Surgeries per Physician Outlier';
      topDriverDesc = `${Math.round(surgCount / mdsCount)} surgeries per attending MD exceeds 99th percentile capacity`;
      topShap = +0.384;
    } else if (losDays > 8.0) {
      topDriverFeature = 'ICU Mean Length of Stay Extension';
      topDriverDesc = `Mean stay of ${losDays} days conflicts with admitted diagnostic package norms`;
      topShap = +0.312;
    } else if (centScore > 0.60) {
      topDriverFeature = 'Bipartite Collusion Centrality';
      topDriverDesc = `High eigenvector centrality (${Math.round(centScore * 100)}%) in cross-admit doctor network`;
      topShap = +0.264;
    } else if (dupRate > 0.20) {
      topDriverFeature = 'Same-Day Duplicate Submissions';
      topDriverDesc = `${Math.round(dupRate * 100)}% same-day duplicate claim submissions flagged`;
      topShap = +0.295;
    }

    return {
      provider_id: row.provider_id || `PRV_${idx + 1}`,
      name: row.name || `Facility ${row.provider_id || idx + 1}`,
      city: row.city || 'India',
      archetype: row.archetype || (isFlagged ? 'Clinical Volume Outlier' : 'Compliant General Healthcare Provider'),
      reimbursement: totalReimb,
      surgeries: surgCount,
      physicians: mdsCount,
      fraud_risk_score: riskScore,
      risk_percentage: `${(riskScore * 100).toFixed(1)}%`,
      confidence_score: confVal.toFixed(1),
      confidence_tier: confTier,
      decision: isFlagged ? 'FLAGGED FOR AUDIT' : 'AUTO-CLEARED',
      priority: priority,
      why_flagged: topDriverDesc,
      directive: isFlagged ? `Freeze pending reimbursements (₹${totalReimb.toLocaleString('en-IN')}) and subpoena clinical logs` : 'Expedited payment approved',
      top_driver: {
        feature: topDriverFeature,
        description: topDriverDesc,
        shap_contribution: topShap,
      },
    };
  });

  return {
    status: 'success',
    dataset_name: datasetName,
    total_evaluated: results.length,
    flagged_count: flaggedCount,
    cleared_count: clearedCount,
    critical_count: criticalCount,
    high_count: highCount,
    total_exposure: totalExposure,
    flagged_exposure: flaggedExposure,
    average_confidence: (results.reduce((acc, r) => acc + Number(r.confidence_score), 0) / (results.length || 1)).toFixed(1),
    results: results,
  };
}
